    // The previous bundle lives at a fixed path that survives the installing
    // process. These tests drive the swap on real files and directories,
    // because "kept in a temp dir that is deleted on return" was the bug.

    #[test]
    fn install_keeps_the_file_it_replaces() {
        let root = tempfile::tempdir().unwrap();
        let current = root.path().join("app.AppImage");
        let previous = root.path().join("cache/updater/previous/app");
        std::fs::write(&current, "old").unwrap();
        std::fs::create_dir_all(previous.parent().unwrap()).unwrap();
        std::fs::write(&previous, "older").unwrap();

        replace_bundle(&current, &previous).unwrap();

        assert!(!current.exists());
        assert_eq!(std::fs::read_to_string(&previous).unwrap(), "old");

        // The update writes the new bundle to the same path.
        std::fs::write(&current, "new").unwrap();
        rollback_previous(&previous, &current).unwrap();

        assert_eq!(std::fs::read_to_string(&current).unwrap(), "old");
        assert!(!previous.exists());
    }

